/// Maps each operand name to its accessor call and value type, for one instruction (bound fields then computed).
/// Computed operands use their deduplicated accessor name from `acc_names`.
fn op_acc(
    acc_names: &HashMap<(String, String), String>,
    inst: &Insn,
) -> BTreeMap<String, (String, FieldTy)> {
    let mut m = BTreeMap::new();

    for f in &inst.fields {
        m.insert(
            f.name.clone(),
            (format!("{}(word)", ident(&f.name)), f.ty.clone()),
        );
    }

    for c in &inst.computed {
        m.insert(
            c.name.clone(),
            (
                format!("{}(word)", comp_acc(acc_names, inst, c)),
                c.ty.clone(),
            ),
        );
    }
    m
}

fn acc_methods(acc: &BTreeMap<String, (String, FieldTy)>) -> BTreeMap<String, String> {
    acc.iter()
        .map(|(k, (m, _))| (k.clone(), m.clone()))
        .collect()
}

/// The hex magnitude expression for a value of type `ty`.
fn hex_magnitude(acc: &str, ty: &FieldTy) -> String {
    if ty.signed {
        let mask = mask_u64(ty.value_width.min(64));
        format!("((unsigned long long)({acc}) & {mask:#x}ull)")
    } else {
        format!("(unsigned long long)({acc})")
    }
}

fn field_write(name: &str, fmt: &FmtSpec, acc: &BTreeMap<String, (String, FieldTy)>) -> String {
    let Some((method, ty)) = acc.get(name) else {
        return format!(
            "snprintf(buf, sizeof buf, \"%lld\", (long long){}(word)); __r += buf; ",
            ident(name)
        );
    };
    render_call_cpp(method, fmt, ty)
}

/// Render a value expression `call` (an integer-typed C++ expression) of type `ty` under `fmt`,
/// emitting statements that append the rendered text to `__r` (using the local `buf` scratch). Used
/// both by bound-field rendering and by subdecoder output rendering.
fn render_call_cpp(call: &str, fmt: &FmtSpec, ty: &FieldTy) -> String {
    if fmt.hex {
        let inner = if fmt.zero_pad > 0 {
            format!("%0{}llx", fmt.zero_pad)
        } else {
            "%llx".to_string()
        };
        let pfx = if fmt.alt { "0x" } else { "" };
        return format!(
            "snprintf(buf, sizeof buf, \"{pfx}{inner}\", {}); __r += buf; ",
            hex_magnitude(call, ty)
        );
    }

    if fmt.dec {
        return dec_write(call, ty);
    }

    match &ty.disp {
        Disp::Pattern(p) => pattern_write(p, call, ty),
        Disp::Hint(DispHint::Hex) => format!(
            "snprintf(buf, sizeof buf, \"0x%llx\", {}); __r += buf; ",
            hex_magnitude(call, ty)
        ),
        Disp::Hint(DispHint::SignedHex) => {
            if ty.signed {
                format!(
                    "{{ long long __v = (long long)({call}); if (__v < 0) snprintf(buf, sizeof buf, \"-0x%llx\", (unsigned long long)(-__v)); else snprintf(buf, sizeof buf, \"0x%llx\", (unsigned long long)__v); __r += buf; }} "
                )
            } else {
                // An unsigned operand is never negative, so signed_hex is just hex magnitude.
                format!(
                    "snprintf(buf, sizeof buf, \"0x%llx\", {}); __r += buf; ",
                    hex_magnitude(call, ty)
                )
            }
        }
        Disp::Hint(DispHint::Dec) => dec_write(call, ty),
        Disp::Names(t) => {
            let default_stmt = match &t.default {
                NameDefault::Str(d) => format!("{{ __r += {}; }}", c_string(d)),
                NameDefault::Hint(DispHint::Dec) => format!("{{ {} }}", dec_write(call, ty)),
                NameDefault::Hint(DispHint::Hex) | NameDefault::Hint(DispHint::SignedHex) => {
                    format!(
                        "{{ snprintf(buf, sizeof buf, \"0x%llx\", {}); __r += buf; }}",
                        hex_magnitude(call, ty)
                    )
                }
            };
            if t.entries.is_empty() {
                default_stmt
            } else {
                let mut s = format!("{{ unsigned long long __nv = (unsigned long long)({call}); ");
                for (k, name) in &t.entries {
                    s.push_str(&format!(
                        "if (__nv == {k}ull) {{ __r += {}; }} else ",
                        c_string(name)
                    ));
                }
                s.push_str(&default_stmt);
                s.push_str(" } ");
                s
            }
        }
        Disp::None => {
            if ty.signed {
                dec_write(call, ty)
            } else {
                format!(
                    "snprintf(buf, sizeof buf, \"0x%llx\", {}); __r += buf; ",
                    hex_magnitude(call, ty)
                )
            }
        }
    }
}

/// Emit a decimal write that respects the operand's signedness. A signed operand
/// prints with %lld. An unsigned one prints with %llu so a high-bit-set value stays positive.
fn dec_write(call: &str, ty: &FieldTy) -> String {
    if ty.signed {
        format!("snprintf(buf, sizeof buf, \"%lld\", (long long)({call})); __r += buf; ")
    } else {
        format!("snprintf(buf, sizeof buf, \"%llu\", (unsigned long long)({call})); __r += buf; ")
    }
}

fn pattern_write(p: &str, call: &str, ty: &FieldTy) -> String {
    let parts: Vec<&str> = p.split("{}").collect();

    let (conv, cast) = if ty.signed {
        ("%lld", "(long long)")
    } else {
        ("%llu", "(unsigned long long)")
    };

    let mut s = String::from("{ ");
    for (i, part) in parts.iter().enumerate() {
        if !part.is_empty() {
            s.push_str(&format!("__r += {}; ", c_string(part)));
        }
        if i + 1 < parts.len() {
            s.push_str(&format!("snprintf(buf, sizeof buf, \"{conv}\", {cast}("));
            s.push_str(call);
            s.push_str(")); __r += buf; ");
        }
    }
    s.push_str("} ");
    s
}

fn seg_stmts(segs: &[Seg], acc: &BTreeMap<String, (String, FieldTy)>) -> String {
    let cond_acc = acc_methods(acc);

    let mut s = String::new();
    for seg in segs {
        match seg {
            Seg::Lit(t) => s.push_str(&format!("__r += {}; ", c_string(t))),
            Seg::Cond { cond, then, els } => {
                s.push_str(&format!(
                    "if (({}) != 0) {{ {}}} else {{ {}}} ",
                    emit_cond(cond, "word", &cond_acc),
                    seg_stmts(then, acc),
                    seg_stmts(els, acc)
                ));
            }
            Seg::Field { name, fmt } => s.push_str(&field_write(name, fmt, acc)),
            Seg::SubField { field, output } => {
                if let Some((method, ty)) = acc.get(field) {
                    if let Some(sdn) = &ty.subdecoder {
                        s.push_str(&format!(
                            "__r += {}((unsigned long long)({method})); ",
                            sub_fn_name_cpp(sdn, output)
                        ));
                    }
                }
            }
        }
    }
    s
}

/// The emitted sub-render function name for a `(subdecoder, output)` pair.
fn sub_fn_name_cpp(subdecoder: &str, output: &str) -> String {
    format!("sub_{}_{}", sanitize(subdecoder), sanitize(output))
}

/// Emit one `std::string sub_<name>_<output>(unsigned long long v)` per subdecoder output: an
/// ordered chain of `if ((v & mask) == val)` arms (most-specific-first) rendering each arm's
/// output template.
fn sub_fns_cpp(isa: &Isa) -> String {
    let mut s = String::new();
    for sd in &isa.subdecoders {
        for oname in &sd.outputs {
            let _ = writeln!(
                s,
                "static inline std::string {}(unsigned long long v) {{",
                sub_fn_name_cpp(&sd.name, oname)
            );
            s.push_str("    char buf[64]; std::string __r; (void)buf; (void)v;\n");
            for arm in &sd.arms {
                let segs = arm.output(oname).unwrap_or(&[]);
                let _ = write!(
                    s,
                    "    if ((v & {:#x}ull) == {:#x}ull) {{ ",
                    arm.mask, arm.val
                );
                sub_segs_cpp(segs, &arm.fields, &mut s);
                s.push_str("return __r; }\n");
            }
            s.push_str("    return __r;\n}\n");
        }
    }
    s
}

fn sub_segs_cpp(segs: &[Seg], fields: &[Field], s: &mut String) {
    for seg in segs {
        match seg {
            Seg::Lit(t) => {
                let _ = write!(s, "__r += {}; ", c_string(t));
            }
            Seg::Field { name, fmt } => {
                if let Some(f) = fields.iter().find(|f| &f.name == name) {
                    let mask = mask_u64(f.range.width());
                    let valexpr = format!("((v >> {}) & {mask:#x}ull)", f.range.lo);
                    s.push_str(&render_call_cpp(&valexpr, fmt, &f.ty));
                }
            }
            // Conditionals and nested sub-fields are rejected in subdecoder outputs at resolution.
            Seg::Cond { .. } | Seg::SubField { .. } => {}
        }
    }
}

fn arms_block(acc_names: &HashMap<(String, String), String>, inst: &Insn) -> String {
    let acc = op_acc(acc_names, inst);
    let cond_acc = acc_methods(&acc);

    let mut code = String::new();
    let mut saw_uncond = false;
    for (i, arm) in inst.display.iter().enumerate() {
        let body = format!(
            "{{ std::string __r; {}return __r; }}",
            seg_stmts(&arm.segs, &acc)
        );
        match &arm.cond {
            Some(c) => {
                let kw = if i == 0 { "if" } else { "else if" };
                code.push_str(&format!(
                    "{kw} (({}) != 0) {body} ",
                    emit_cond(c, "word", &cond_acc)
                ));
            }
            None => {
                if i == 0 {
                    code.push_str(&body);
                } else {
                    code.push_str(&format!("else {body} "));
                }
                saw_uncond = true;
                break;
            }
        }
    }
    if !saw_uncond {
        code.push_str(&format!("return {};", c_string(&inst.name)));
    }

    code
}

fn disasm_fn(isa: &Isa, m: &Model) -> String {
    let handle = handle_ty(isa);
    let acc_names = computed_accessor_names(isa);
    let mut s = String::new();

    if m.modal {
        let _ = writeln!(
            s,
            "static inline std::string disasm(unsigned combo, {handle} word) {{"
        );
    } else {
        let _ = writeln!(s, "static inline std::string disasm({handle} word) {{");
    }
    s.push_str("    char buf[64];\n    (void)buf;\n");

    if m.modal {
        s.push_str("    switch (classify(combo, word)) {\n");
    } else {
        s.push_str("    switch (classify(word)) {\n");
    }
    for &idx in &isa.instr_order() {
        let inst = &isa.instrs[idx];
        let _ = writeln!(s, "    case OP_{}: {{", cname(&inst.name));
        let _ = writeln!(s, "        {}", arms_block(&acc_names, inst));
        s.push_str("    }\n");
    }
    s.push_str("    default: return \"(invalid)\";\n    }\n}\n");

    s
}
